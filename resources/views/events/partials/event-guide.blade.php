<x-ui.guide-modal title="Panduan Event">
    Halaman event mengumpulkan identitas kegiatan dan susunan panitianya. Hak Anda di sini mengikuti jabatan Anda dalam panitia.
    <x-slot:steps>
        <li>Lengkapi identitas, tanggal, tujuan, dan indikator di tab <strong>Ringkasan</strong>.</li>
        <li>Susun pengurus inti dan seksi di tab <strong>Panitia</strong>. Orang yang ditugaskan menerima undangan dan baru mendapat akses setelah menerimanya.</li>
        <li>Event diaktifkan setelah semua jabatan wajib terisi oleh panitia yang sudah bersedia.</li>
    </x-slot:steps>
    <x-slot:notes>
        <li>Ketua dan pengawas ditetapkan oleh organisasi. Pengurus lain dapat ditetapkan oleh pengelola kepanitiaan, dan koordinator seksi dapat menambahkan anggota di seksinya.</li>
        <li>Seorang pengawas tidak dapat sekaligus menjadi pelaksana dalam panitia yang sama.</li>
        <li>Mencabut keanggotaan seseorang langsung menutup aksesnya ke event ini.</li>
        <li>Setiap perubahan status, jabatan, dan keanggotaan tercatat beserta pelakunya.</li>
    </x-slot:notes>
</x-ui.guide-modal>
