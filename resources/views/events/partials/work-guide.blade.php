<x-ui.guide-modal title="Panduan Program & Tugas">
    Program kerja adalah rencana tiap seksi; tugas adalah pekerjaan nyata untuk menjalankannya. Hak Anda di sini mengikuti jabatan Anda dalam panitia.
    <x-slot:steps>
        <li>Koordinator seksi menyusun <strong>program kerja</strong> seksinya: tujuan, keluaran, indikator, dan periode.</li>
        <li>Pengelola tugas membuat <strong>tugas</strong> dan subtugas, menetapkan penanggung jawab, tenggat, dan besar pekerjaannya (ringan, sedang, berat).</li>
        <li>Setelah pekerjaan beres, penanggung jawab menekan <strong>Tandai Selesai</strong>, menulis hasilnya, dan mengunggah foto atau dokumen pendukung. Tugas langsung selesai, tanpa persetujuan.</li>
        <li>Semua panitia dapat melihat tugas seksi mana pun dan memberi <strong>komentar</strong>.</li>
    </x-slot:steps>
    <x-slot:notes>
        <li>Tugas tidak dapat diselesaikan selama tugas prasyaratnya atau subtugasnya belum selesai.</li>
        <li>Hasil pekerjaan wajib diisi saat menandai selesai, dan masih bisa diubah atau dilengkapi fotonya sesudahnya.</li>
        <li>Progres dihitung dari tugas yang sudah selesai. Tugas berat dihitung tiga kali tugas ringan, tugas sedang dua kali. Tugas yang dipecah menjadi subtugas dihitung dari subtugasnya.</li>
        <li>Bukti hanya dapat diunduh oleh orang yang boleh melihat tugasnya.</li>
    </x-slot:notes>
</x-ui.guide-modal>
