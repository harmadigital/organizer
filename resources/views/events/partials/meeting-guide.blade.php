<x-ui.guide-modal title="Panduan Rapat & Notulen">
    Rapat dan notulen dapat dilihat oleh semua panitia. Tidak ada undangan atau konfirmasi hadir: rapat yang dijadwalkan langsung muncul untuk semua.
    <x-slot:steps>
        <li>Sekretaris (untuk pengurus inti) atau koordinator seksi (untuk seksinya) menjadwalkan rapat beserta agendanya.</li>
        <li>Setelah rapat, penulis notulen mengisi <strong>notulen</strong>: isi rapat, siapa yang hadir, keputusan, dan tindak lanjut.</li>
        <li>Begitu disimpan, notulen langsung dapat dibaca semua panitia, dan setiap tindak lanjut otomatis menjadi <strong>tugas</strong> di Program &amp; Tugas.</li>
    </x-slot:steps>
    <x-slot:notes>
        <li>Notulen tetap bisa diperbaiki; setiap simpanan tercatat di tab Riwayat.</li>
        <li>Semua panitia dapat memberi komentar pada rapat.</li>
        <li>Rapat yang sudah memiliki notulen tidak dapat dihapus.</li>
    </x-slot:notes>
</x-ui.guide-modal>
