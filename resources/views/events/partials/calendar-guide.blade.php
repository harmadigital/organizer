<x-ui.guide-modal title="Panduan Kalender">
    Kalender menampilkan semua jadwal event dalam satu tempat: hari pelaksanaan, rapat, tenggat tugas, dan kegiatan panitia seperti survei lokasi atau latihan.
    <x-slot:steps>
        <li><strong>Rapat</strong> dan <strong>tenggat tugas</strong> muncul sendiri dari Rapat &amp; Notulen dan Program &amp; Tugas.</li>
        <li>Klik jadwal untuk melihat ringkasannya: tanggal, tempat, siapa yang mengerjakan, dan keadaannya. Dari situ tekan <strong>Buka halaman rapat</strong> atau <strong>Buka halaman tugas</strong> bila ingin melihat semuanya.</li>
        <li>Semua panitia bisa menambah <strong>kegiatan</strong> lewat tombol Tambah Kegiatan, atau dengan mengklik tanggal di tampilan Bulan.</li>
        <li>Pilih seksi di atas kalender untuk melihat jadwal satu seksi saja.</li>
    </x-slot:steps>
    <x-slot:notes>
        <li>Kegiatan diubah atau dihapus oleh yang menambahkannya, Sekretaris (untuk Pengurus Inti), atau koordinator seksinya.</li>
        <li>Kegiatan beberapa hari dicatat seharian, tanpa jam.</li>
        <li>Setelah event selesai, kalender tidak bisa diubah lagi.</li>
        <li>Jadwal dari semua event yang Anda ikuti ada di menu <strong>Kalender Saya</strong>.</li>
    </x-slot:notes>
</x-ui.guide-modal>
